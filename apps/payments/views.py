"""Member-facing seal purchase screens: choose seal, pay, status."""

from django.conf import settings
from django.contrib import messages
from django.http import Http404, JsonResponse
from django.shortcuts import get_object_or_404, redirect, render
from django.utils.safestring import mark_safe
from django.utils.translation import gettext as _
from django.utils.translation import gettext_lazy
from django.views.decorators.cache import never_cache
from django.views.decorators.http import require_http_methods, require_POST, require_safe

from apps.core.decorators import member_required
from apps.memberships.models import SealTier
from apps.memberships.selectors import membership_selector

from . import promptpay
from .forms import SlipUploadForm
from .models import PaymentIntent
from .selectors import payment_selector
from .services import payment_service

STATUS_COPY = {
    PaymentIntent.Status.VERIFYING: gettext_lazy("Checking your slip. This usually takes under a minute."),
    PaymentIntent.Status.REVIEW: gettext_lazy("Your slip is being checked by our team."),
    PaymentIntent.Status.APPROVED: gettext_lazy("Payment confirmed. Your seal is active."),
    PaymentIntent.Status.EXPIRED: gettext_lazy("This payment window has expired. Please start again."),
    PaymentIntent.Status.CANCELLED: gettext_lazy("This payment was cancelled."),
    PaymentIntent.Status.REJECTED: gettext_lazy("This payment was not accepted."),
}


@never_cache
@member_required
@require_http_methods(["GET", "POST"])
def choose_seal(request):
    if request.method == "POST":
        tier = get_object_or_404(SealTier, code=request.POST.get("tier", ""), is_active=True)
        try:
            intent = payment_service.start_checkout(request.user, tier)
        except payment_service.PaymentError as exc:
            messages.error(request, str(exc))
            return redirect("payments:choose_seal")
        return redirect("payments:pay", reference=intent.reference)

    context = {
        "tiers": membership_selector.all_active_tiers(),
        "current": membership_selector.current_membership(request.user),
        "open_intent": payment_selector.open_intent(request.user),
        "active_tab": "portal",
    }
    return render(request, "payments/choose_seal.html", context)


@never_cache
@member_required
@require_safe
def pay(request, reference):
    intent = payment_service.expire_if_due(payment_selector.member_intent_or_404(request.user, reference))
    promptpay_svg = None
    if intent.status == PaymentIntent.Status.AWAITING_SLIP and settings.PROMPTPAY_ID:
        # Generated by us from config and the amount: safe to inline.
        promptpay_svg = mark_safe(  # noqa: S308
            promptpay.render_svg(promptpay.build_payload(settings.PROMPTPAY_ID, intent.amount_satang))
        )
    context = {
        "intent": intent,
        "form": SlipUploadForm(),
        "promptpay_svg": promptpay_svg,
        "status_text": STATUS_COPY.get(intent.status, ""),
        "bank": {
            "name": settings.PAYMENT_BANK_NAME,
            "number": settings.PAYMENT_BANK_ACCOUNT_NUMBER,
            "holder": settings.PAYMENT_BANK_ACCOUNT_NAME,
        },
        "active_tab": "portal",
    }
    return render(request, "payments/pay.html", context)


@member_required
@require_POST
def upload_slip(request, reference):
    intent = payment_selector.member_intent_or_404(request.user, reference)
    form = SlipUploadForm(request.POST, request.FILES)
    if not form.is_valid():
        messages.error(request, _("Please choose an image of your transfer slip."))
        return redirect("payments:pay", reference=reference)
    try:
        payment_service.submit_slip(intent, form.cleaned_data["slip"])
    except payment_service.PaymentError as exc:
        messages.error(request, str(exc))
    return redirect("payments:pay", reference=reference)


@member_required
@require_POST
def cancel(request, reference):
    intent = payment_selector.member_intent_or_404(request.user, reference)
    try:
        payment_service.cancel_checkout(intent)
    except payment_service.PaymentError as exc:
        messages.error(request, str(exc))
        return redirect("payments:pay", reference=reference)
    messages.info(request, _("Payment cancelled."))
    return redirect("payments:choose_seal")


@never_cache
@require_safe
def status(request, reference):
    """Small JSON endpoint polled by the Pay screen while a slip is checked."""
    if not request.user.is_authenticated or not request.user.is_verified:
        raise Http404
    intent = payment_service.expire_if_due(payment_selector.member_intent_or_404(request.user, reference))
    return JsonResponse(
        {
            "status": intent.status,
            "message": str(intent.status_message or STATUS_COPY.get(intent.status, "")),
            "done": not intent.is_open or intent.status == PaymentIntent.Status.AWAITING_SLIP,
        }
    )
